/**
 * ============================================================================
 * SERVICE PAGES - ARABIC
 * ============================================================================
 * Mirrors `data/service-lines.ts`, one export per page. Types come from the
 * English modules, so a renamed or reshaped field is a compile error here
 * rather than a hole on an Arabic page.
 *
 * ----------------------------------------------------------------------------
 * WHAT STAYS AS IT IS
 * ----------------------------------------------------------------------------
 * - `slug`, `href`, `key` - identifiers and routes.
 * - `number` - Western numerals.
 * - "Gulf Connect" - a registered name, in Latin script inside Arabic
 *   sentences, as Gulf corporate Arabic does.
 * - Place names take their established Arabic forms: دبي، أبوظبي، الرياض.
 *
 * ----------------------------------------------------------------------------
 * TERMINOLOGY
 * ----------------------------------------------------------------------------
 *   investor roadshow             -> جولة المستثمرين
 *   one-to-one meetings           -> اجتماعات ثنائية
 *   hosted group session          -> جلسة جماعية مستضافة
 *   briefing pack                 -> حزمة إحاطة
 *   earned / paid / owned media   -> الإعلام المكتسب / المدفوع / المملوك
 *   certified financial translation -> ترجمة مالية معتمدة
 *   disclosure                    -> الإفصاح   (the regulatory term)
 *   listing                       -> الإدراج
 *
 * The three media layers keep the industry's own vocabulary rather than a
 * descriptive paraphrase. The separation between them is a compliance
 * distinction, and a paraphrase blurs the line it exists to hold.
 *
 * ----------------------------------------------------------------------------
 * COMPLIANCE - THE FOUR PASSAGES THAT CARRY THE MOST WEIGHT
 * ----------------------------------------------------------------------------
 * 1. `investorRoadshows.notWhatWeDo`. Three categorical denials, verbatim
 *    client-approved copy in English. The Arabic states the same three, in the
 *    same order, at the same force: we do not solicit investment, we take no
 *    success fees, we guarantee no outcomes. A denial must not soften into a
 *    preference.
 *
 * 2. `mediaArabic.honestLine`. Verbatim client-approved copy. Editorial
 *    coverage is decided by the publication; the fee is for the work and not
 *    the outcome; be sceptical of any firm that says otherwise. The em dash is
 *    preserved. Do not shorten or split it.
 *
 * 3. `mediaArabic.reach.disclaimer`. Sits under a map of six markets. It
 *    denies offices, registrations AND media relationships, and states that no
 *    coverage is guaranteed. All four survive in the Arabic.
 *
 * 4. `mediaArabic.layers`. "يقررها المحرّر وحده" and "يُفصح عنه دائمًا" are the
 *    clauses the whole separation rests on. Neither may be dropped.
 *
 * AWAITING LEGAL REVIEW. The four passages above are compliance statements.
 * The Arabic is a faithful rendering, but that is a judgement a translator
 * with the relevant standing has to certify. See `legalReviewRequired` in
 * `content/dictionary.ts`.
 */

